class PreparationError(Exception):
    """An actionable input, inference, or publication failure."""


def require(condition: bool, message: str) -> None:
    if not condition:
        raise PreparationError(message)


def number(value: Any, label: str, minimum: float | None = None,
           maximum: float | None = None) -> float:
    require(type(value) in (int, float), f'{label} must be a finite number.')
    try:
        result = float(value)
    except (ValueError, OverflowError) as exc:
        raise PreparationError(f'{label} must be finite.') from exc
    require(math.isfinite(result), f'{label} must be finite.')
    require(minimum is None or result >= minimum, f'{label} is below its minimum.')
    require(maximum is None or result <= maximum, f'{label} is above its maximum.')
    return result


def integer(value: Any, label: str, minimum: int = 0) -> int:
    require(type(value) is int and minimum <= value <= 2**53 - 1,
            f'{label} must be a safe integer at least {minimum}.')
    return value


def text(value: Any, label: str) -> str:
    require(isinstance(value, str) and bool(value.strip()), f'{label} must be nonempty text.')
    return value


def plate_key(raw: str | None) -> str:
    normalized = re.sub(r'[\s._/-]+', '', (raw or '').upper())
    # Uncertainty symbols are not separators and must not disappear into a DB match.
    return normalized if normalized.isalnum() else ''


def ocr_confidence(value: Any, label: str) -> float | list[float] | None:
    if value is None:
        return None
    if isinstance(value, list):
        return [number(item, label, 0, 1) for item in value]
    return number(value, label, 0, 1)


def unique_object(pairs: list[tuple[str, Any]]) -> dict:
    result: dict = {}
    for key, value in pairs:
        require(key not in result, f'Duplicate JSON key: {key!r}.')
        result[key] = value
    return result


def invalid_constant(value: str) -> None:
    raise PreparationError(f'Non-finite JSON constant: {value}.')


def parse_json(content: str, label: str) -> Any:
    try:
        return json.loads(content, object_pairs_hook=unique_object,
                          parse_constant=invalid_constant)
    except (ValueError, RecursionError) as exc:
        raise PreparationError(f'Invalid JSON in {label}: {exc}') from exc


def input_file(value: str | Path) -> Path:
    path = Path(value).expanduser().resolve()
    require(path.is_file(), f'Missing input file: {path}')
    require(path.stat().st_size > 0, f'Empty input file: {path}')
    return path


def load_json(path: Path) -> Any:
    return parse_json(path.read_text(encoding='utf-8-sig'), str(path))


def output_file(value: str | Path, inputs: list[Path], force: bool) -> Path:
    original = Path(value).expanduser()
    require(not original.is_symlink(), f'Output must not be a symbolic link: {original}')
    path = original.resolve()
    for source in inputs:
        same = path == source or (path.exists() and os.path.samefile(path, source))
        require(not same, f'Output must never replace an input file: {source}')
    require(path.parent.is_dir(), f'Output directory does not exist: {path.parent}')
    require(not path.exists() or path.is_file(), f'Output is not a regular file: {path}')
    require(force or not path.exists(), f'Output exists: {path}. Use --force to replace it.')
    return path


def publish(path: Path, content: str, inputs: list[Path], force: bool) -> None:
    output_file(path, inputs, force)
    temporary: Path | None = None
    try:
        with tempfile.NamedTemporaryFile(mode='w', encoding='utf-8', newline='\n',
                                         dir=path.parent, prefix='.taxtrack-',
                                         suffix='.tmp', delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        output_file(path, inputs, force)
        if force:
            os.replace(temporary, path)
        else:
            # Unlike rename on POSIX, link atomically refuses an existing destination.
            os.link(temporary, path)
    finally:
        if temporary is not None and temporary.exists():
            temporary.unlink()


def media_mime(path: Path, header: bytes | None = None) -> str:
    mime = MIMES.get(path.suffix.lower())
    require(mime is not None, f'Unsupported video extension: {path}. Use MP4/M4V or WebM.')
    if header is None:
        with path.open('rb') as stream:
            header = stream.read(4096)
    if mime == 'video/mp4':
        valid = (len(header) >= 16 and header[4:8] == b'ftyp'
                 and int.from_bytes(header[:4], 'big') >= 16 and header[8:12] != b'qt  ')
    else:
        valid = header.startswith(b'\x1a\x45\xdf\xa3') and b'webm' in header[:4096]
    require(valid, f'Video container signature does not match {mime}: {path}. '
            'Use a genuine supported container, not a renamed file.')
    return mime


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open('rb') as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b''):
            digest.update(chunk)
    return digest.hexdigest()


def validate_envelope(envelope: Any, expected_ids: set[str] | None = None,
                      embedded: bool = False) -> None:
    require(isinstance(envelope, dict) and set(envelope) == {'schemaVersion', 'sources'},
            'Expected an envelope containing only schemaVersion and sources.')
    require(type(envelope['schemaVersion']) is int and envelope['schemaVersion'] == 1,
            'Unsupported schemaVersion; expected integer 1.')
    require(isinstance(envelope['sources'], list), 'sources must be an array.')
    ids: set[str] = set()
    for source in envelope['sources']:
        require(isinstance(source, dict) and set(source) == SOURCE_FIELDS,
                'A source has missing or unexpected fields.')
        sid = source['id']
        require(isinstance(sid, str) and sid in SOURCES and sid not in ids,
                'Source IDs must be unique closeup/traffic values.')
        ids.add(sid)
        require(source['cameraId'] == SOURCES[sid][1], f'{sid}: incorrect cameraId.')
        text(source['name'], f'{sid}.name')
        require(source['mime'] in tuple(MIMES.values()), f'{sid}: unsupported video MIME.')
        require(isinstance(source['videoSha256'], str)
                and re.fullmatch(r'[0-9a-f]{64}', source['videoSha256']) is not None,
                f'{sid}: videoSha256 must be lowercase SHA-256 hex.')
        if embedded:
            text(source['videoBase64'], f'{sid}.videoBase64')
        else:
            require(source['videoBase64'] is None, f'{sid}: extraction videoBase64 must be null.')
        width = integer(source['width'], f'{sid}.width', 1)
        height = integer(source['height'], f'{sid}.height', 1)
        count = integer(source['frameCount'], f'{sid}.frameCount', 1)
        fps = number(source['fps'], f'{sid}.fps', 0)
        require(fps > 0, f'{sid}: fps must be positive.')
        duration = number(source['durationSeconds'], f'{sid}.durationSeconds', 0)
        require(math.isclose(duration, count / fps, rel_tol=1e-7, abs_tol=1e-7),
                f'{sid}: durationSeconds must equal frameCount / fps.')
        frames, tracks = source['frames'], source['tracks']
        require(isinstance(frames, list) and len(frames) == count,
                f'{sid}: frames length does not match frameCount.')
        require(isinstance(tracks, dict), f'{sid}: tracks must be an object.')
        require(isinstance(source['provenance'], dict), f'{sid}: provenance must be an object.')
        for tid, track in tracks.items():
            require(isinstance(tid, str) and TRACK_ID.fullmatch(tid) is not None,
                    f'{sid}: track IDs must be positive integer strings.')
            require(isinstance(track, dict) and set(track) == TRACK_FIELDS,
                    f'{sid}/{tid}: missing or unexpected track fields.')
            first = integer(track['firstFrame'], f'{sid}/{tid}.firstFrame')
            last = integer(track['lastFrame'], f'{sid}/{tid}.lastFrame')
            evidence = integer(track['evidenceFrame'], f'{sid}/{tid}.evidenceFrame')
            require(first <= evidence <= last < count, f'{sid}/{tid}: invalid frame range.')
            text(track['vehicleId'], f'{sid}/{tid}.vehicleId')
            raw, plate, origin = track['rawOcr'], track['plate'], track['plateSource']
            require(raw is None or isinstance(raw, str), f'{sid}/{tid}: rawOcr must be text/null.')
            ocr_confidence(track['ocrConfidence'], f'{sid}/{tid}.ocrConfidence')
            require(origin in ('ocr', 'demo_assigned', 'unreadable'),
                    f'{sid}/{tid}: invalid plateSource.')
            if origin == 'unreadable':
                require(plate is None, f'{sid}/{tid}: unreadable plate must be null.')
            else:
                text(plate, f'{sid}/{tid}.plate')
                require(bool(plate_key(plate)), f'{sid}/{tid}: plate has no letters or digits.')
                if origin == 'ocr':
                    require(raw is not None and plate_key(raw) == plate_key(plate),
                            f'{sid}/{tid}: OCR plate must agree with preserved rawOcr.')
        observed: dict[str, list] = {}
        for index, detections in enumerate(frames):
            require(isinstance(detections, list), f'{sid}: frame {index} must be an array.')
            seen: set[str] = set()
            for detection in detections:
                require(isinstance(detection, list) and len(detection) == 6,
                        f'{sid}: invalid detection tuple at frame {index}.')
                tid, x1, y1, x2, y2, confidence = detection
                require(isinstance(tid, str) and tid in tracks and tid not in seen,
                        f'{sid}: missing/duplicate track reference at frame {index}.')
                seen.add(tid)
                x1, y1, x2, y2 = [number(v, f'{sid} frame {index} coordinate')
                                  for v in (x1, y1, x2, y2)]
                require(0 <= x1 < x2 <= width and 0 <= y1 < y2 <= height,
                        f'{sid}: invalid exclusive bounds at frame {index}.')
                number(confidence, f'{sid} frame {index} detectorConfidence', 0, 1)
                state = observed.setdefault(tid, [index, index, False])
                state[1] = index
                state[2] = state[2] or index == tracks[tid]['evidenceFrame']
        require(set(observed) == set(tracks), f'{sid}: unobserved tracks are not permitted.')
        for tid, (first, last, has_evidence) in observed.items():
            track = tracks[tid]
            require(first == track['firstFrame'] and last == track['lastFrame'] and has_evidence,
                    f'{sid}/{tid}: frame range/evidenceFrame does not match observed boxes.')
    require(expected_ids is None or ids == expected_ids, 'Unexpected or missing source IDs.')


@dataclass
class Reading:
    frame: int
    raw: str | None
    confidence: float | list[float] | None
    detector_confidence: float

    def score(self) -> tuple:
        values = self.confidence if isinstance(self.confidence, list) else [self.confidence]
        usable = [value for value in values if value is not None]
        mean = sum(usable) / len(usable) if usable else -1.0
        return (bool(self.raw and self.raw.strip()), mean, self.detector_confidence, -self.frame)


@dataclass
class Candidate:
    votes: int
    reading: Reading


@dataclass
class Track:
    tid: str
    first: int
    last: int
    center: tuple[float, float]
    candidates: dict[str, Candidate] = field(default_factory=dict)
    fallback: Reading | None = None

    def observe(self, index: int, detection: dict) -> None:
        self.last = index
        self.center = detection['center']
        reading = Reading(index, detection['raw'], detection['ocr'], detection['confidence'])
        if self.fallback is None or reading.score() > self.fallback.score():
            self.fallback = reading
        key = plate_key(reading.raw)
        if not key:
            return
        if key not in self.candidates and len(self.candidates) == 8:
            # Misra-Gries bounded voting: decrement on overflow, never invent votes.
            for existing in list(self.candidates):
                self.candidates[existing].votes -= 1
                if self.candidates[existing].votes == 0:
                    del self.candidates[existing]
            return
        if key not in self.candidates:
            self.candidates[key] = Candidate(0, reading)
        candidate = self.candidates[key]
        candidate.votes += 1
        if reading.score() > candidate.reading.score():
            candidate.reading = reading

    def record(self) -> dict:
        winner = max(self.candidates.values(),
                     key=lambda item: (item.votes, item.reading.score()), default=None)
        reading = winner.reading if winner is not None else self.fallback
        require(reading is not None, f'Track {self.tid} has no observed evidence.')
        plate = plate_key(reading.raw) or None
        return {'plate': plate, 'plateSource': 'ocr' if plate else 'unreadable',
                'rawOcr': reading.raw, 'ocrConfidence': reading.confidence,
                'firstFrame': self.first, 'lastFrame': self.last,
                'evidenceFrame': reading.frame, 'vehicleId': self.tid}


class CentroidTracker:
    def __init__(self, distance: float, max_missed: int):
        self.distance_squared = distance * distance
        self.max_missed = max_missed
        self.next_id = 1
        self.active: dict[str, Track] = {}
        self.finished: dict[str, dict] = {}

    def update(self, index: int, detections: list[dict]) -> list[list]:
        for tid, track in list(self.active.items()):
            if index - track.last - 1 > self.max_missed:
                self.finished[tid] = track.record()
                del self.active[tid]
        edges = []
        for tid, track in self.active.items():
            for position, detection in enumerate(detections):
                cx, cy = detection['center']
                squared = (cx - track.center[0]) ** 2 + (cy - track.center[1]) ** 2
                if squared <= self.distance_squared:
                    edges.append((squared, int(tid), position))
        used: set[str] = set()
        matches: dict[int, str] = {}
        for _, numeric_id, position in sorted(edges):
            tid = str(numeric_id)
            if tid not in used and position not in matches:
                used.add(tid)
                matches[position] = tid
        frame = []
        for position, detection in enumerate(detections):
            tid = matches.get(position)
            if tid is None:
                tid = str(self.next_id)
                self.next_id += 1
                self.active[tid] = Track(tid, index, index, detection['center'])
            self.active[tid].observe(index, detection)
            frame.append([tid, *detection['bounds'], detection['confidence']])
        return frame

    def finish(self) -> dict[str, dict]:
        for tid, track in self.active.items():
            self.finished[tid] = track.record()
        self.active.clear()
        return dict(sorted(self.finished.items(), key=lambda pair: int(pair[0])))


class TimestampCheck:
    def __init__(self, fps: float):
        self.interval_ms = 1000.0 / fps
        self.tolerance_ms = max(1.0, self.interval_ms * 0.02)
        self.valid = self.missing = self.zeros = 0
        self.positive = False
        self.previous: tuple[int, float] | None = None
        self.maximum_error = 0.0

    def observe(self, index: int, timestamp: float) -> None:
        if not math.isfinite(timestamp) or timestamp < 0:
            self.missing += 1
            self.previous = None
            return
        self.valid += 1
        if timestamp == 0:
            require(not self.positive, f'Timestamp regressed at frame {index}. {NORMALIZE_GUIDANCE}')
            self.zeros += 1
        else:
            require(self.zeros <= 1, f'Repeated timestamps before frame {index}. {NORMALIZE_GUIDANCE}')
            self.positive = True
            error = abs(timestamp - index * self.interval_ms)
            self.maximum_error = max(self.maximum_error, error)
            require(error <= self.tolerance_ms,
                    f'Non-CFR or nonzero-start timestamp at frame {index}: {timestamp:.6f} ms. '
                    f'{NORMALIZE_GUIDANCE}')
        if self.previous is not None:
            previous_index, previous_time = self.previous
            if timestamp != 0 or previous_time != 0:
                require(timestamp > previous_time,
                        f'Non-increasing timestamp at frame {index}. {NORMALIZE_GUIDANCE}')
                error = abs(timestamp - previous_time - (index - previous_index) * self.interval_ms)
                self.maximum_error = max(self.maximum_error, error)
                require(error <= self.tolerance_ms,
                        f'Irregular timestamp interval at frame {index}. {NORMALIZE_GUIDANCE}')
        self.previous = (index, timestamp)

    def finish(self, count: int, assume: bool) -> dict:
        unavailable = self.missing > 0 or count < 2 or not self.positive
        require(not unavailable or assume,
                'CFR timestamps could not be verified. Independently confirm upright CFR input, '
                'then use --assume-cfr, or export a new zero-start CFR file.')
        return {'status': 'assumed' if unavailable else 'verified',
                'assumeCfrRequested': assume, 'validTimestampCount': self.valid,
                'missingTimestampCount': self.missing, 'zeroTimestampCount': self.zeros,
                'intervalMs': self.interval_ms, 'toleranceMs': self.tolerance_ms,
                'maximumErrorMs': self.maximum_error,
                'method': 'CAP_PROP_POS_MSEC after every decoded frame; interval and zero-origin checks'}


def capture_metadata(capture: Any, cv2: Any) -> dict:
    require(capture.isOpened(), 'Video could not be opened; it may be corrupt or use an unsupported codec.')
    require(capture.getBackendName() == 'FFMPEG',
            'An FFmpeg OpenCV backend is required to validate orientation. Use the isolated environment.')
    require(hasattr(cv2, 'CAP_PROP_ORIENTATION_META') and hasattr(cv2, 'CAP_PROP_ORIENTATION_AUTO'),
            'OpenCV lacks orientation metadata controls. Use the documented isolated environment.')
    require(capture.set(cv2.CAP_PROP_ORIENTATION_AUTO, 0),
            'Could not disable automatic video rotation; source coordinates would be unsafe.')
    require(capture.get(cv2.CAP_PROP_ORIENTATION_AUTO) == 0,
            'Automatic video rotation is still enabled; upright source pixels cannot be guaranteed.')
    rotation = number(capture.get(cv2.CAP_PROP_ORIENTATION_META), 'Video rotation')
    require(abs(rotation % 360) < 1e-6, f'Video rotation metadata is {rotation} degrees. {NORMALIZE_GUIDANCE}')
    sar_num = number(capture.get(cv2.CAP_PROP_SAR_NUM), 'Pixel aspect numerator', 0)
    sar_den = number(capture.get(cv2.CAP_PROP_SAR_DEN), 'Pixel aspect denominator', 0)
    require(sar_num == 0 or (sar_den > 0 and math.isclose(sar_num / sar_den, 1.0)),
            'Non-square pixels can misalign browser evidence crops. Export square-pixel upright CFR media to a NEW file.')
    result = {'rotationDegrees': rotation, 'automaticRotation': False, 'backend': 'FFMPEG',
              'sampleAspectRatio': [sar_num, sar_den]}
    for name, property_id in (('width', cv2.CAP_PROP_FRAME_WIDTH),
                              ('height', cv2.CAP_PROP_FRAME_HEIGHT),
                              ('declaredFrameCount', cv2.CAP_PROP_FRAME_COUNT)):
        value = number(capture.get(property_id), name, 1)
        require(abs(value - round(value)) < 0.001,
                f'Unreliable {name} metadata. {NORMALIZE_GUIDANCE}')
        result[name] = integer(round(value), name, 1)
    fps = number(capture.get(cv2.CAP_PROP_FPS), 'Video FPS', 0)
    require(fps > 0 and math.isfinite(1000.0 / fps), 'Missing or invalid video FPS metadata.')
    result['fps'] = fps
    return result


def prediction_records(results: Any, width: int, height: int, index: int) -> list[dict]:
    require(isinstance(results, list), f'Frame {index}: predict did not return a result list.')
    records = []
    try:
        for result in results:
            box = result.detection.bounding_box
            coords = [number(value, f'Frame {index} bounding box')
                      for value in (box.x1, box.y1, box.x2, box.y2)]
            require(coords[0] < coords[2] and coords[1] < coords[3],
                    f'Frame {index}: inverted or empty detector bounds.')
            x1, y1 = max(0, min(width, math.floor(coords[0]))), max(0, min(height, math.floor(coords[1])))
            x2, y2 = max(0, min(width, math.ceil(coords[2]))), max(0, min(height, math.ceil(coords[3])))
            require(x1 < x2 and y1 < y2, f'Frame {index}: detector bounds lie outside source pixels.')
            confidence = number(result.detection.confidence, f'Frame {index} detector confidence', 0, 1)
            ocr = result.ocr
            raw = ocr.text if ocr is not None else None
            require(raw is None or isinstance(raw, str), f'Frame {index}: OCR text is invalid.')
            score = ocr_confidence(ocr.confidence if ocr is not None else None,
                                   f'Frame {index} OCR confidence')
            records.append({'bounds': (x1, y1, x2, y2), 'confidence': confidence,
                            'center': ((x1 + x2) / 2, (y1 + y2) / 2), 'raw': raw, 'ocr': score})
    except (AttributeError, TypeError, ValueError) as exc:
        raise PreparationError(f'Frame {index}: invalid ALPR result: {exc}') from exc
    return sorted(records, key=lambda item: (*item['bounds'], -item['confidence'], item['raw'] or '',
                                            json.dumps(item['ocr'])))


def assignments_file(path: Path | None) -> dict[str, str]:
    if path is None:
        return {}
    assignments = load_json(path)
    require(isinstance(assignments, dict), 'Assignments must map track ID strings to sample plate strings.')
    for tid, plate in assignments.items():
        require(TRACK_ID.fullmatch(tid) is not None, f'Invalid assignment track ID: {tid!r}.')
        text(plate, f'Assignment {tid}')
        require(bool(plate_key(plate)), f'Assignment {tid} has no letters or digits.')
    return assignments


def extract(args: argparse.Namespace) -> None:
    video = input_file(args.video)
    assignment_path = input_file(args.demo_assignments) if args.demo_assignments else None
    inputs = [video] + ([assignment_path] if assignment_path is not None else [])
    output = output_file(args.output, inputs, args.force)
    assignments = assignments_file(assignment_path)
    mime = media_mime(video)
    distance = number(args.max_distance, '--max-distance', 0)
    require(distance > 0 and math.isfinite(distance * distance), '--max-distance must be positive and finite.')
    integer(args.max_missed, '--max-missed')
    initial_hash = sha256_file(video)
    initial_bytes = video.stat().st_size
    try:
        version = metadata.version('fast-alpr')
        require(version == '0.4.0', f'Expected fast-alpr 0.4.0, found {version}. Use the isolated environment.')
        import cv2
        from fast_alpr import ALPR
    except (ImportError, metadata.PackageNotFoundError) as exc:
        raise PreparationError('Extraction needs the isolated Python 3.12 environment with '
                               '"fast-alpr[onnx]==0.4.0". See the module docstring.') from exc
    capture = None
    frames: list[list] = []
    tracker = CentroidTracker(distance, args.max_missed)
    model = None
    try:
        capture = cv2.VideoCapture(str(video), cv2.CAP_FFMPEG)
        info = capture_metadata(capture, cv2)
        timing = TimestampCheck(info['fps'])
        while True:
            index = len(frames)
            ok, frame = capture.read()
            if not ok:
                require(index == info['declaredFrameCount'],
                        f'Decoding ended at frame {index}; metadata declares {info["declaredFrameCount"]}. '
                        f'Input may be truncated/corrupt or have unreliable metadata. {NORMALIZE_GUIDANCE}')
                break
            require(frame is not None and frame.ndim == 3 and frame.shape[2] == 3,
                    f'Frame {index}: decoder did not return a BGR image.')
            require(frame.shape[:2] == (info['height'], info['width']),
                    f'Frame {index}: dimensions changed or orientation is ambiguous. {NORMALIZE_GUIDANCE}')
            timestamp = float(capture.get(cv2.CAP_PROP_POS_MSEC))
            timing.observe(index, timestamp)
            if model is None:
                try:
                    model = ALPR(detector_model=DETECTOR, ocr_model=OCR_MODEL,
                                 detector_conf_thresh=THRESHOLD, detector_providers=PROVIDERS.copy(),
                                 ocr_device='cpu', ocr_providers=PROVIDERS.copy())
                except Exception as exc:
                    raise PreparationError('ALPR initialization failed (first use may need model downloads): '
                                           f'{exc}') from exc
            try:
                results = model.predict(frame)
            except Exception as exc:
                raise PreparationError(f'ALPR inference failed at frame {index}: {exc}') from exc
            detections = prediction_records(results, info['width'], info['height'], index)
            frames.append(tracker.update(index, detections))
        require(bool(frames), 'No frames decoded; input is empty or corrupt.')
        timestamp_report = timing.finish(len(frames), args.assume_cfr)
    except PreparationError:
        raise
    except Exception as exc:
        raise PreparationError(f'Video extraction failed near frame {len(frames)}: {exc}') from exc
    finally:
        if capture is not None:
            capture.release()
    require(sha256_file(video) == initial_hash and video.stat().st_size == initial_bytes,
            'Source video changed during extraction; discard this run and retry with stable input.')
    tracks = tracker.finish()
    require(not (set(assignments) - set(tracks)),
            f'Assignment IDs were not observed: {sorted(set(assignments) - set(tracks))}. No output written.')
    for tid, plate in assignments.items():
        tracks[tid]['plate'] = plate
        tracks[tid]['plateSource'] = 'demo_assigned'
    versions = {}
    for package in ('fast-alpr', 'fast-plate-ocr', 'onnxruntime', 'opencv-python-headless'):
        try:
            versions[package] = metadata.version(package)
        except metadata.PackageNotFoundError:
            versions[package] = None
    source = {'id': args.source_id, 'name': SOURCES[args.source_id][0],
              'cameraId': SOURCES[args.source_id][1], 'mime': mime, 'videoBase64': None,
              'videoSha256': initial_hash, 'width': info['width'], 'height': info['height'],
              'fps': info['fps'], 'frameCount': len(frames),
              'durationSeconds': len(frames) / info['fps'], 'frames': frames, 'tracks': tracks,
              'provenance': {'tool': 'prepare_videos.py', 'schemaVersion': 1,
                             'createdUtc': datetime.now(timezone.utc).isoformat(),
                             'inputFileName': video.name, 'videoByteLength': initial_bytes,
                             'pythonVersion': sys.version.split()[0], 'packages': versions,
                             'opencvVersion': cv2.__version__, 'detectorModel': DETECTOR,
                             'ocrModel': OCR_MODEL, 'detectorConfidenceThreshold': THRESHOLD,
                             'detectorProviders': PROVIDERS, 'ocrDevice': 'cpu', 'ocrProviders': PROVIDERS,
                             'capture': info, 'timestampChecks': timestamp_report,
                             'tracking': {'method': 'greedy one-to-one centroid',
                                          'maxDistancePixels': distance, 'maxMissedFrames': args.max_missed,
                                          'idPolicy': 'monotonic, never recycled',
                                          'ocrCandidateLimit': 8, 'ocrVoting': 'Misra-Gries bounded votes',
                                          'evidenceSelection': 'votes, OCR mean confidence, detector confidence, earliest'},
                             'demoAssignments': assignments,
                             'inferenceFrameCount': len(frames), 'hashCheckedAfterExtraction': True}}
    envelope = {'schemaVersion': 1, 'sources': [source]}
    validate_envelope(envelope, {args.source_id})
    publish(output, json.dumps(envelope, ensure_ascii=True, allow_nan=False, separators=(',', ':')) + '\n',
            inputs, args.force)
    print(f'Extracted {len(frames)} frames and {len(tracks)} plate tracks to {output}')


class TemplateAudit(HTMLParser):
    """Locate actual HTML markers and the single inert data script, not string lookalikes."""

    BLOCKED = {'script', 'style', 'textarea', 'title', 'template', 'noscript',
               'xmp', 'iframe', 'noembed', 'plaintext', 'svg', 'math'}

    def __init__(self, document: str):
        super().__init__(convert_charrefs=True)
        self.offsets = [0, *(match.end() for match in re.finditer('\n', document))]
        self.blocked: list[str] = []
        self.markers: dict[str, list[int]] = {' TAXTRACK_DATA_BEGIN ': [], ' TAXTRACK_DATA_END ': []}
        self.targets = 0
        self.target_active = False
        self.script_start = self.body_start = self.body_end = self.script_end = -1
        self.document = document

    def source_offset(self) -> int:
        line, column = self.getpos()
        return self.offsets[line - 1] + column

    def handle_comment(self, data: str) -> None:
        if data in self.markers:
            require(not self.blocked, 'Data markers must be active HTML comments, outside raw/inert elements.')
            self.markers[data].append(self.source_offset())

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        if any(key == 'id' and value == 'taxtrack-data' for key, value in attrs):
            self.targets += 1
            require(tag == 'script' and not self.blocked, 'taxtrack-data must be one top-level inert JSON script.')
            require(len(dict(attrs)) == len(attrs), 'Duplicate attributes on the data script are unsafe.')
            attributes = dict(attrs)
            require((attributes.get('type') or '').lower() == 'application/json' and 'src' not in attributes,
                    'taxtrack-data must have type application/json and no src attribute.')
            self.target_active = True
            self.script_start = self.source_offset()
            self.body_start = self.script_start + len(self.get_starttag_text())
        if tag in self.BLOCKED:
            self.blocked.append(tag)

    def handle_endtag(self, tag: str) -> None:
        if tag == 'script' and self.target_active:
            self.body_end = self.source_offset()
            self.script_end = self.document.find('>', self.body_end) + 1
            self.target_active = False
        if tag in self.blocked:
            reverse_index = self.blocked[::-1].index(tag)
            del self.blocked[len(self.blocked) - reverse_index - 1:]


def replace_data(document: str, envelope: dict) -> str:
    require(document.count(BEGIN) == 1 and document.count(END) == 1,
            'Template must contain exactly one occurrence of each exact TAXTRACK_DATA marker.')
    begin, end = document.index(BEGIN), document.index(END)
    require(begin < end, 'Template data markers are reversed.')
    audit = TemplateAudit(document)
    audit.feed(document)
    audit.close()
    require(audit.markers[' TAXTRACK_DATA_BEGIN '] == [begin]
            and audit.markers[' TAXTRACK_DATA_END '] == [end],
            'Markers must be real, unambiguous HTML comments, not strings or nested comments.')
    require(audit.targets == 1 and begin + len(BEGIN) <= audit.script_start < audit.body_start
            <= audit.body_end < audit.script_end <= end,
            'Exactly one closed taxtrack-data script must be entirely between the markers.')
    require(not document[begin + len(BEGIN):audit.script_start].strip()
            and not document[audit.script_end:end].strip(),
            'Only the inert data script and whitespace may appear between the markers.')
    previous = parse_json(document[audit.body_start:audit.body_end], 'template data script')
    require(isinstance(previous, dict) and set(previous) == {'schemaVersion', 'sources'}
            and type(previous['schemaVersion']) is int and previous['schemaVersion'] == 1
            and isinstance(previous['sources'], list), 'Template data script must contain a version 1 envelope.')
    payload = json.dumps(envelope, ensure_ascii=True, allow_nan=False, separators=(',', ':')).replace('<', '\\u003c')
    script = '\n<script id="taxtrack-data" type="application/json">' + payload + '</script>\n'
    return document[:begin + len(BEGIN)] + script + document[end:]


def embed(args: argparse.Namespace) -> None:
    template = input_file(args.template)
    paths = {sid: (input_file(getattr(args, sid + '_video')), input_file(getattr(args, sid + '_data')))
             for sid in SOURCES}
    inputs = [template, *(path for pair in paths.values() for path in pair)]
    output = output_file(args.output, inputs, args.force)
    document = template.read_text(encoding='utf-8-sig')
    # Validate template before allocating base64 media buffers.
    replace_data(document, {'schemaVersion': 1, 'sources': []})
    sources = []
    for sid, (video, data) in paths.items():
        envelope = load_json(data)
        validate_envelope(envelope, {sid})
        source = envelope['sources'][0]
        raw = video.read_bytes()
        require(hashlib.sha256(raw).hexdigest() == source['videoSha256'],
                f'{sid}: video SHA-256 does not match extraction data. Re-extract this exact video.')
        require(media_mime(video, raw[:4096]) == source['mime'], f'{sid}: video MIME differs from extraction.')
        length = source['provenance'].get('videoByteLength')
        require(length is None or (type(length) is int and length == len(raw)),
                f'{sid}: video byte length differs from extraction provenance.')
        source['videoBase64'] = base64.b64encode(raw).decode('ascii')
        source['provenance']['embedding'] = {'hashVerified': True, 'videoByteLength': len(raw),
                                            'createdUtc': datetime.now(timezone.utc).isoformat()}
        del raw
        sources.append(source)
    combined = {'schemaVersion': 1, 'sources': sources}
    validate_envelope(combined, set(SOURCES), embedded=True)
    publish(output, replace_data(document, combined), inputs, args.force)
    print(f'Embedded both hash-verified videos into {output}')


def parser() -> argparse.ArgumentParser:
    cli = argparse.ArgumentParser(description='Extract genuine plate evidence or embed two videos into offline HTML.',
                                  epilog='See the module docstring for exact isolated Python 3.12 PowerShell setup.')
    commands = cli.add_subparsers(dest='command', required=True)
    extraction = commands.add_parser('extract', help='Run fast-alpr once on every decoded BGR frame.')
    extraction.add_argument('--video', required=True, help='Upright zero-start CFR MP4/M4V or WebM.')
    extraction.add_argument('--source-id', required=True, choices=tuple(SOURCES))
    extraction.add_argument('--output', required=True, help='New extraction JSON envelope.')
    extraction.add_argument('--demo-assignments', help='Reviewed JSON map of track IDs to explicit sample plates.')
    extraction.add_argument('--assume-cfr', action='store_true',
                            help='Explicitly accept unavailable timestamps, never observed irregularity.')
    extraction.add_argument('--max-distance', type=float, default=80.0, help='Centroid distance gate in pixels (default: 80).')
    extraction.add_argument('--max-missed', type=int, default=12, help='Allowed absent frames before expiry (default: 12).')
    extraction.add_argument('--force', action='store_true', help='Replace an existing output, never any input.')
    extraction.set_defaults(action=extract)
    embedding = commands.add_parser('embed', help='Hash-check and embed both real videos; standard library only.')
    embedding.add_argument('--template', required=True, help='HTML with exact data markers and one inert JSON script.')
    for sid in SOURCES:
        embedding.add_argument('--' + sid + '-video', required=True, help=f'Exact {sid} video used for extraction.')
        embedding.add_argument('--' + sid + '-data', required=True, help=f'One-source {sid} extraction JSON.')
    embedding.add_argument('--output', required=True, help='New self-contained HTML file, e.g. TaxTrackAI.html.')
    embedding.add_argument('--force', action='store_true', help='Replace an existing output, never any input.')
    embedding.set_defaults(action=embed)
    return cli


def main(argv: list[str] | None = None) -> int:
    args = parser().parse_args(argv)
    try:
        args.action(args)
        return 0
    except (PreparationError, OSError, UnicodeError, ValueError, RecursionError) as exc:
        print(f'Error: {exc}', file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        print('Cancelled; no completed output was published.', file=sys.stderr)
        return 130


if __name__ == '__main__':
    raise SystemExit(main())
